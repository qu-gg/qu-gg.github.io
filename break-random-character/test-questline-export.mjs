import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { rollCharacter } from "./generator.mjs";
import {
    buildQuestlinePackage,
    currencyFromStones,
} from "./questline-export.mjs";

const data = JSON.parse(await readFile(new URL("./data.json", import.meta.url), "utf8"));
const exporterSource = await readFile(new URL("./questline-export.mjs", import.meta.url), "utf8");

function seededRandom(seed) {
    let state = seed >>> 0;
    return () => {
        state = (state * 1664525 + 1013904223) >>> 0;
        return state / 4294967296;
    };
}

function readUint16(bytes, offset) {
    return bytes[offset] | bytes[offset + 1] << 8;
}

function readUint32(bytes, offset) {
    return (bytes[offset]
        | bytes[offset + 1] << 8
        | bytes[offset + 2] << 16
        | bytes[offset + 3] << 24) >>> 0;
}

function readStoredZip(bytes) {
    const decoder = new TextDecoder();
    const files = {};
    let offset = 0;
    while (offset + 4 <= bytes.length && readUint32(bytes, offset) === 0x04034b50) {
        const compressedSize = readUint32(bytes, offset + 18);
        const nameLength = readUint16(bytes, offset + 26);
        const extraLength = readUint16(bytes, offset + 28);
        const nameStart = offset + 30;
        const dataStart = nameStart + nameLength + extraLength;
        const name = decoder.decode(bytes.slice(nameStart, dataStart - extraLength));
        const content = bytes.slice(dataStart, dataStart + compressedSize);
        files[name] = decoder.decode(content);
        offset = dataStart + compressedSize;
    }
    return files;
}

function generatedCharacter(seed, contentMode, rank) {
    return rollCharacter(data, seededRandom(seed), {}, contentMode, 75, true, rank);
}

function validatePackage(character) {
    const packageData = buildQuestlinePackage(character, data, { exportedAt: "2026-08-30T00:00:00.000Z" });
    const entity = packageData.entities.characters[0];
    const serialized = JSON.stringify(packageData.entities);
    const items = entity.sheetData.inventory.items;
    const weaponActions = items.flatMap((item) => item.actions).filter((action) => action.type === "Weapons");
    const sourceWeapons = [...character.gear, ...character.purchasedGear].filter((item) => item.gearCategory === "weapons");

    assert.deepEqual(Object.keys(packageData.files).sort(), ["entities.json", "manifest.json"]);
    assert.deepEqual(readStoredZip(packageData.zip), packageData.files);
    assert.equal(packageData.zip[0], 0x50);
    assert.equal(packageData.zip[1], 0x4b);
    assert.equal(packageData.manifest.format, "questline-package");
    assert.equal(packageData.manifest.type, "characters");
    assert.equal(packageData.manifest.totalAssetSize, 0);
    assert.deepEqual(packageData.manifest.assetMap, {});
    assert.equal(packageData.entities.characters.length, 1);
    assert.equal(entity.version, 9);
    assert.equal(entity.activeSheet, "JhUsxZOelsROtFyksRAP");
    assert.equal(entity.id.length, 20);
    assert.equal(entity.name, character.name);
    assert.equal(entity.sheetData.bio.name, character.name);
    assert.equal(entity.sheetData.bio.subname, character.calling.name);
    assert.equal(entity.sheetData.bio.species, character.species.name);
    assert.equal(entity.sheetData.bio.homeland, character.homeland.name);
    assert.match(entity.sheetData.bio.details, new RegExp(character.history.name));
    assert.equal(entity.sheetData.bio.languages, character.languages.join(", "));
    const backgroundLines = entity.sheetData.bio.background.split("\n\n");
    assert.equal(backgroundLines[0], `Rank: ${character.rank}`);
    assert.match(backgroundLines[1], /^Size: /);
    assert.ok(!entity.sheetData.bio.background.includes("Generated by"));
    assert.ok(!entity.sheetData.bio.background.includes("Quirk Category"));
    assert.equal(entity.sheetData["rank-and-xp"].attributes["rank-and-xp"].rank.value, String(character.rank));
    assert.deepEqual(entity.sheetData.inventory.currency, currencyFromStones(character.shopping.totalCurrencyStones));
    assert.equal(entity.sheetData.inventory.maxEncumbrance, Math.round(character.combat.inventory));
    assert.equal(entity.sheetData.hearts.max, character.combat.hearts);
    assert.equal(entity.sheetData.hearts.current, character.combat.hearts);
    assert.equal(entity.sheetData["attack-bonus"].attributes["attack-bonus"].value.value, String(character.combat.attack));
    assert.equal(entity.sheetData["defense-rating"].attributes["defense-rating"].value.value, String(character.combat.defense));
    assert.equal(entity.sheetData["speed-rating"].attributes["speed-rating"].value.value, String({ Slow: 0, Average: 1, Fast: 2, "Very Fast": 3 }[character.combat.speed]));
    assert.equal(items.length, [...character.gear, ...character.purchasedGear].filter((item) => !item.currencyStones).length);
    assert.equal(weaponActions.length, sourceWeapons.length);
    assert.ok(weaponActions.every((action) => action.effects[0].modifiers[0].linkedValue === "attack-bonus.attributes.attack-bonus.value.value"));
    assert.ok(weaponActions.every((action) => action.effects[0].baseRoll === "1d20"));
    assert.equal(entity.sheetData.actions.length, 0);
    assert.ok(entity.sheetData["quirk-and-abilities"].every((feature) => feature.description.type === "doc"));
    assert.ok(entity.sheetData["quirk-and-abilities"].every((feature) => feature.description.content.every((block) => block.type === "paragraph")));
    assert.ok(entity.sheetData["quirk-and-abilities"].every((feature) => JSON.stringify(feature.description).includes("Complete this feature in Questline.")));
    for (const feature of entity.sheetData["quirk-and-abilities"]) {
        const parts = feature.subtext ? feature.subtext.split(" · ") : [];
        assert.equal(new Set(parts).size, parts.length);
        assert.ok(!feature.subtext?.startsWith(`${feature.type} ·`));
    }
    assert.ok(entity.sheetData["quirk-and-abilities"].length >= character.abilities.calling.length + character.abilities.species.length + 1);
    assert.ok(weaponActions.every((action) => action.details.some((detail) => detail.value?.description?.includes("Complete this weapon Action in Questline."))));
    assert.ok(items.every((item) => item.isCustom && item.type === "none" && Array.isArray(item.actions)));
    assert.ok(items.every((item) => item.description.length === 0 || item.description.includes("Source:") || item.description.includes("Nickname:")));
    for (const aptitude of ["might", "deftness", "grit", "insight", "aura"]) {
        const bonusValue = entity.sheetData.aptitudes.attributes.aptitudes[aptitude].bonusValue;
        const traits = character.traits.filter((trait) => trait.aptitude === aptitude);
        const modifiers = character.modifiers.aptitudes[aptitude] ?? [];
        const bonusParts = [...traits, ...modifiers];
        if (bonusParts.length) {
            const expectedBonusValue = bonusParts.map(({ amount }) => `${bonusParts.length > 1 && amount > 0 ? "+" : ""}${amount}`).join("/");
            assert.equal(bonusValue, expectedBonusValue, `${aptitude} should format positive bonuses for Questline`);
        }
        if (!traits.length && !modifiers.length) assert.equal(entity.sheetData.aptitudes.attributes.aptitudes[aptitude].bonusText, ".");
    }
    assert.ok(serialized.includes("Resolved Choices:"));
    assert.ok(!serialized.includes("questline-vtt-tools"));
    assert.ok(!serialized.includes("BREAK!! Test OCR"));

    const repeated = buildQuestlinePackage(character, data, { exportedAt: "2026-08-30T00:00:00.000Z" });
    assert.deepEqual(repeated.entities, packageData.entities);
    assert.deepEqual(repeated.files, packageData.files);
    assert.deepEqual(repeated.zip, packageData.zip);
}

assert.ok(!exporterSource.includes("questline-vtt-tools"));
assert.ok(!exporterSource.includes("BREAK!! Test OCR"));
validatePackage(generatedCharacter(0xC0FFEE, "core", 1));
validatePackage(generatedCharacter(0xB4EA5, "expanded", 10));

const formattingCharacter = generatedCharacter(0x51A1, "core", 1);
formattingCharacter.traits = [{ aptitude: "might", amount: 1 }];
for (const aptitude of Object.keys(formattingCharacter.modifiers.aptitudes)) formattingCharacter.modifiers.aptitudes[aptitude] = [];
const formattingPackage = () => buildQuestlinePackage(formattingCharacter, data, { exportedAt: "2026-08-30T00:00:00.000Z" });
assert.equal(formattingPackage().entity.sheetData.aptitudes.attributes.aptitudes.might.bonusValue, "1");
formattingCharacter.traits.push({ aptitude: "might", amount: -1 });
assert.equal(formattingPackage().entity.sheetData.aptitudes.attributes.aptitudes.might.bonusValue, "+1/-1");

for (let seed = 1; seed <= 100; seed += 1) {
    const mode = seed % 2 ? "core" : "expanded";
    const rank = seed % 10 + 1;
    const character = rollCharacter(data, seededRandom(seed), {}, mode, 0, false, rank);
    const packageData = buildQuestlinePackage(character, data, { exportedAt: "2026-08-30T00:00:00.000Z" });
    assert.equal(packageData.entities.characters.length, 1);
    assert.ok(packageData.zip.length > 1000);
}

